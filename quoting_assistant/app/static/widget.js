/* Quoting assistant chat widget.
 * Embed with one tag:
 *   <script src="https://HOST/widget.js" data-client="demo_shop" data-lang="ca" async></script>
 * Optional: data-color="#0b5cad"  data-privacy-url="https://client.example/privacitat"
 */
(function () {
  "use strict";
  var me = document.currentScript || (function () {
    var s = document.querySelectorAll("script[data-client]"); return s[s.length - 1];
  })();
  if (!me || window.__quoteWidgetLoaded) return;
  window.__quoteWidgetLoaded = true;

  var API = new URL(me.src, location.href).origin;
  var CLIENT = me.getAttribute("data-client");
  var COLOR = me.getAttribute("data-color") || "#0b5cad";
  var PRIVACY = me.getAttribute("data-privacy-url") || "";
  var nav = (navigator.language || "ca").slice(0, 2);
  var LANG = me.getAttribute("data-lang") || (["ca", "es", "en", "fr"].indexOf(nav) >= 0 ? nav : "ca");
  var STORE_KEY = "qa_conv_" + CLIENT;

  var UI = {
    ca: { launch: "Demanin pressupost", sub: "Assistent virtual · IA", ph: "Escriguin el seu missatge…", attach: "Adjuntar plànol", send: "Enviar",
          foot: "Respostes generades per IA. Els preus són orientatius i pendents de revisió.", privacy: "Privacitat", sample: "Tarifes de mostra (demo)", err: "Error de connexió. Tornin-ho a provar." },
    es: { launch: "Pidan presupuesto", sub: "Asistente virtual · IA", ph: "Escriban su mensaje…", attach: "Adjuntar plano", send: "Enviar",
          foot: "Respuestas generadas por IA. Los precios son orientativos y pendientes de revisión.", privacy: "Privacidad", sample: "Tarifas de muestra (demo)", err: "Error de conexión. Vuelvan a intentarlo." },
    en: { launch: "Get a quote", sub: "Virtual assistant · AI", ph: "Type your message…", attach: "Attach drawing", send: "Send",
          foot: "Answers generated by AI. Prices are indicative and pending review.", privacy: "Privacy", sample: "Sample rates (demo)", err: "Connection error. Please try again." },
    fr: { launch: "Demander un devis", sub: "Assistant virtuel · IA", ph: "Écrivez votre message…", attach: "Joindre un plan", send: "Envoyer",
          foot: "Réponses générées par IA. Les prix sont indicatifs et à vérifier.", privacy: "Confidentialité", sample: "Tarifs d'exemple (démo)", err: "Erreur de connexion. Veuillez réessayer." }
  };

  var CSS = [
    ":host{all:initial;--c:" + COLOR + ";--bg:#fff;--ink:#1d232b;--muted:#5d6774;--line:#e2e6eb;--bot:#f1f3f6;--card:#f7faf8;--ok:#0b7a4b}",
    "@media (prefers-color-scheme:dark){:host{--bg:#1b2128;--ink:#e8ecf1;--muted:#9aa5b1;--line:#2f3843;--bot:#252d36;--card:#1f2a25}}",
    "*{box-sizing:border-box;font-family:system-ui,-apple-system,'Segoe UI',Roboto,sans-serif}",
    ".launch{position:fixed;right:20px;bottom:20px;z-index:2147483000;background:var(--c);color:#fff;border:0;border-radius:28px;padding:14px 20px;font-size:15px;font-weight:600;box-shadow:0 6px 20px rgba(0,0,0,.22);cursor:pointer;display:flex;gap:8px;align-items:center}",
    ".panel{position:fixed;right:20px;bottom:20px;z-index:2147483001;width:380px;max-width:calc(100vw - 32px);height:600px;max-height:calc(100vh - 40px);background:var(--bg);color:var(--ink);border-radius:14px;box-shadow:0 12px 40px rgba(0,0,0,.28);display:none;flex-direction:column;overflow:hidden;border:1px solid var(--line)}",
    ".panel.open{display:flex}",
    "@media (max-width:480px){.panel{right:0;bottom:0;width:100vw;max-width:100vw;height:100%;max-height:100%;border-radius:0}}",
    ".hd{background:var(--c);color:#fff;padding:12px 14px;display:flex;align-items:center;gap:10px}",
    ".hd .t{flex:1;min-width:0}.hd b{display:block;font-size:15px;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}.hd small{opacity:.9;font-size:12px}",
    ".hd select{background:rgba(255,255,255,.18);color:#fff;border:1px solid rgba(255,255,255,.4);border-radius:6px;padding:3px 4px;font-size:12px}",
    ".hd select option{color:#000}.x{background:none;border:0;color:#fff;font-size:22px;cursor:pointer;line-height:1;padding:0 4px}",
    ".msgs{flex:1;overflow-y:auto;padding:14px;display:flex;flex-direction:column;gap:10px}",
    ".m{max-width:86%;padding:9px 12px;border-radius:12px;font-size:14px;line-height:1.45;white-space:pre-wrap;word-wrap:break-word}",
    ".m.bot{background:var(--bot);align-self:flex-start;border-bottom-left-radius:4px}",
    ".m.user{background:var(--c);color:#fff;align-self:flex-end;border-bottom-right-radius:4px}",
    ".m.file{font-style:italic}.m.file:before{content:'📎 '}",
    ".card{align-self:stretch;border:1px solid var(--line);border-left:4px solid var(--ok);background:var(--card);border-radius:10px;padding:12px 14px;font-size:13px}",
    ".card .ti{font-size:12px;text-transform:uppercase;letter-spacing:.04em;color:var(--muted);font-weight:600}",
    ".card .pr{font-size:26px;font-weight:700;margin:4px 0 2px;font-variant-numeric:tabular-nums}",
    ".card .pu{color:var(--muted)}.card ul{margin:8px 0 0;padding-left:18px;color:var(--ink)}.card li{margin:2px 0}",
    ".card .cf{display:inline-block;margin-top:6px;padding:2px 8px;border-radius:10px;background:var(--bot);font-size:12px}",
    ".card .sm{margin-top:6px;font-size:11px;color:var(--muted)}",
    ".typing{align-self:flex-start;color:var(--muted);font-size:13px;padding:4px 2px}",
    ".in{display:flex;gap:6px;padding:10px;border-top:1px solid var(--line);align-items:flex-end}",
    ".in textarea{flex:1;resize:none;border:1px solid var(--line);border-radius:10px;padding:9px 10px;font-size:14px;max-height:110px;background:var(--bg);color:var(--ink)}",
    ".in button{border:0;border-radius:10px;height:38px;min-width:38px;cursor:pointer;font-size:16px}",
    ".att{background:var(--bot);color:var(--ink)}.snd{background:var(--c);color:#fff;padding:0 12px;font-size:14px!important;font-weight:600}",
    ".ft{font-size:11px;color:var(--muted);padding:0 12px 8px;text-align:center}.ft a{color:var(--muted)}"
  ].join("\n");

  var host = document.createElement("div");
  host.id = "quote-assistant";
  document.body.appendChild(host);
  var root = host.attachShadow({ mode: "open" });
  root.innerHTML = "<style>" + CSS + "</style>" +
    '<button class="launch" part="launcher"><span>💬</span><span class="lt"></span></button>' +
    '<div class="panel" role="dialog" aria-label="Chat">' +
    '<div class="hd"><div class="t"><b class="nm">…</b><small class="sub"></small></div>' +
    '<select class="lg" aria-label="Language"><option value="ca">CA</option><option value="es">ES</option><option value="en">EN</option><option value="fr">FR</option></select>' +
    '<button class="x" aria-label="Close">×</button></div>' +
    '<div class="msgs" aria-live="polite"></div>' +
    '<div class="in"><button class="att" type="button">📎</button><input class="fi" type="file" hidden accept=".dxf,.dwg,.step,.stp,.pdf,.png,.jpg,.jpeg,.webp">' +
    '<textarea rows="1"></textarea><button class="snd" type="button"></button></div>' +
    '<div class="ft"></div></div>';

  var $ = function (s) { return root.querySelector(s); };
  var panel = $(".panel"), msgs = $(".msgs"), ta = $("textarea"), fileIn = $(".fi"), lg = $(".lg");
  var convId = null, busy = false;

  function store(k, v) { try { if (v === undefined) return localStorage.getItem(k); if (v === null) localStorage.removeItem(k); else localStorage.setItem(k, v); } catch (e) { return null; } }

  function applyLang() {
    var u = UI[LANG] || UI.en;
    $(".lt").textContent = u.launch; $(".sub").textContent = u.sub; ta.placeholder = u.ph;
    $(".att").title = u.attach; $(".snd").textContent = u.send; lg.value = LANG;
    $(".ft").innerHTML = "";
    $(".ft").appendChild(document.createTextNode(u.foot + " "));
    if (PRIVACY) { var a = document.createElement("a"); a.href = PRIVACY; a.target = "_blank"; a.rel = "noopener"; a.textContent = u.privacy; $(".ft").appendChild(a); }
  }

  function el(tag, cls, text) { var e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; }

  function render(m) {
    if (m.kind === "estimate" && m.payload) {
      var p = m.payload, c = el("div", "card");
      c.appendChild(el("div", "ti", p.title));
      c.appendChild(el("div", "pr", p.low_fmt + " – " + p.high_fmt + " €"));
      if (p.per_unit) c.appendChild(el("div", "pu", "≈ " + p.per_unit.toFixed(2).replace(".", LANG === "en" ? "." : ",") + " € " + p.per_unit_label));
      c.appendChild(el("span", "cf", p.confidence_label));
      if (p.notes && p.notes.length) { var ul = el("ul"); p.notes.forEach(function (n) { ul.appendChild(el("li", null, n)); }); c.appendChild(ul); }
      if (p.sample_values) c.appendChild(el("div", "sm", (UI[LANG] || UI.en).sample));
      msgs.appendChild(c);
    } else if (m.text) {
      msgs.appendChild(el("div", "m " + (m.role === "user" ? "user" : "bot") + (m.kind === "file" ? " file" : ""), m.text));
    }
    msgs.scrollTop = msgs.scrollHeight;
  }

  function typing(on) {
    var t = $(".typing");
    if (on && !t) { msgs.appendChild(el("div", "typing", "…")); msgs.scrollTop = msgs.scrollHeight; }
    if (!on && t) t.remove();
  }

  function call(path, opts) {
    return fetch(API + path, opts).then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); });
  }

  function start(lang) {
    msgs.innerHTML = "";
    return call("/api/" + encodeURIComponent(CLIENT) + "/conversations", {
      method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ lang: lang })
    }).then(function (d) {
      convId = d.conversation_id; store(STORE_KEY, convId); $(".nm").textContent = d.client_name;
      d.messages.forEach(render);
    });
  }

  function resume() {
    var saved = store(STORE_KEY);
    if (!saved) return start(LANG);
    return call("/api/conversations/" + saved).then(function (d) {
      convId = saved; LANG = d.lang || LANG; applyLang(); $(".nm").textContent = d.client_name; d.messages.forEach(render);
    }).catch(function () { store(STORE_KEY, null); return start(LANG); });
  }

  function send(path, opts, userMsg) {
    if (busy || !convId) return;
    busy = true; if (userMsg) render(userMsg); typing(true);
    call(path, opts).then(function (d) { typing(false); d.messages.forEach(render); })
      .catch(function () { typing(false); render({ role: "assistant", kind: "text", text: (UI[LANG] || UI.en).err }); })
      .then(function () { busy = false; });
  }

  function sendText() {
    var text = ta.value.trim(); if (!text) return; ta.value = ""; ta.style.height = "";
    send("/api/conversations/" + convId + "/messages",
      { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ text: text }) },
      { role: "user", kind: "text", text: text });
  }

  $(".launch").addEventListener("click", function () {
    panel.classList.add("open"); $(".launch").style.display = "none";
    if (!convId) resume();
    setTimeout(function () { ta.focus(); }, 50);
  });
  $(".x").addEventListener("click", function () { panel.classList.remove("open"); $(".launch").style.display = ""; });
  $(".snd").addEventListener("click", sendText);
  ta.addEventListener("keydown", function (e) { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); sendText(); } });
  ta.addEventListener("input", function () { ta.style.height = "auto"; ta.style.height = Math.min(ta.scrollHeight, 110) + "px"; });
  $(".att").addEventListener("click", function () { fileIn.click(); });
  fileIn.addEventListener("change", function () {
    var f = fileIn.files[0]; if (!f) return; fileIn.value = "";
    var fd = new FormData(); fd.append("file", f);
    send("/api/conversations/" + convId + "/files", { method: "POST", body: fd }, { role: "user", kind: "file", text: f.name });
  });
  lg.addEventListener("change", function () { LANG = lg.value; applyLang(); store(STORE_KEY, null); start(LANG); });

  // Let the host page open the chat (e.g. a "Request a quote" button): window.QuoteAssistant.open()
  window.QuoteAssistant = { open: function () { $(".launch").click(); } };
  applyLang();
})();
