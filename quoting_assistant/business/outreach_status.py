"""Build business/outreach.md (funnel + per-company status) from prospects.csv and outreach_log.csv.
Run after every update:  python business/outreach_status.py"""
import csv
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
rows = list(csv.DictReader(open(HERE / "prospects.csv", encoding="utf-8")))
log = list(csv.DictReader(open(HERE / "outreach_log.csv", encoding="utf-8")))

contacted = [r for r in rows if r["first_email_date"]]
replied = [r for r in contacted if r["reply_1_date"] or r["reply_2_date"]]
second = [r for r in contacted if r["second_email_date"]]
optout = [r for r in rows if r["opt_out_date"]]
pending = [r for r in rows if not r["first_email_date"] and r["batch"] not in ("Reserve",)]

def row(r):
    reply = "; ".join(x for x in (r["reply_1_date"] and f"{r['reply_1_date']}: {r['reply_1_summary']}",
                                   r["reply_2_date"] and f"{r['reply_2_date']}: {r['reply_2_summary']}") if x) or "—"
    return f"| {r['company']} | {r['town']} | {r['fit']} | {r['first_email_date'] or '—'} | {r['second_email_date'] or '—'} | {reply} | {r['status']} | {r['next_step'] or '—'} |"

by_batch = Counter(r["batch"] for r in rows)
md = f"""# Outreach status

> Generated by `python business/outreach_status.py` from `prospects.csv` and `outreach_log.csv`. Don't edit by hand.

## Funnel

| Stage | Firms |
|---|---|
| Contacted (first email) | {len(contacted)} |
| Second email sent | {len(second)} |
| Replied | {len(replied)} ({', '.join(r['company'] for r in replied) or '—'}) |
| Opted out | {len(optout)} ({', '.join(r['company'] for r in optout) or '—'}) |
| Researched, not contacted yet | {len(pending)} |

Batches: {', '.join(f'{k} ({v})' for k, v in sorted(by_batch.items()))}.

## Contacted firms

| Company | Town | Fit | 1st email | 2nd email | Replies | Status | Next step |
|---|---|---|---|---|---|---|---|
{chr(10).join(row(r) for r in contacted)}

## Latest events

| Date | Company | Type | Summary |
|---|---|---|---|
{chr(10).join(f"| {e['date']} | {e['company']} | {e['direction']} {e['type']} | {e['summary']} |" for e in sorted(log, key=lambda e: e['date'], reverse=True)[:25])}
"""
(HERE / "outreach.md").write_text(md, encoding="utf-8")
print(f"contacted {len(contacted)}, second email {len(second)}, replied {len(replied)}, opted out {len(optout)}, not yet contacted {len(pending)}")
