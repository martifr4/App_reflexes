"""Build business/pricing.md from business/pricing.yaml: prices, unit economics, break-even."""
from pathlib import Path
import math
import yaml

HERE = Path(__file__).resolve().parent
c = yaml.safe_load((HERE / "pricing.yaml").read_text(encoding="utf-8"))
t, mix, v, fx, ads = c["tiers"], c["mix"], c["variable_cost_per_client"], c["fixed_monthly"], c["ads_addon"]
rate = c["our_hourly_rate"]

def eur(x): return f"{x:,.0f} €".replace(",", ".")

# average revenue per client per month (setup spread over lifetime)
tier_rev = sum(mix[k] * (t[k]["monthly"] + t[k]["setup"] / c["months_per_client"]) for k in t)
ads_rev = mix["ads_share"] * (ads["monthly"] + ads["setup"] / c["months_per_client"]
                              + ads["bonus_per_qualified_lead"] * mix["qualified_leads_per_ads_client"])
revenue = tier_rev + ads_rev
llm = v["conversations"] * v["llm_usd_per_conversation"] * v["usd_to_eur"]
cash_var = llm + v["whatsapp_bsp_eur"] + v["whatsapp_templates_eur"]
time_var = (v["our_hours"] + c["setup_hours_per_client"] / c["months_per_client"]) * rate
fixed = sum(fx.values())
margin_cash = revenue - cash_var
margin_full = revenue - cash_var - time_var
be_cash = math.ceil(fixed / margin_cash) if margin_cash > 0 else None
be_full = math.ceil(fixed / margin_full) if margin_full > 0 else None
fo = c["founders"]
founder_cost = fo["count"] * (fo["autonomo_quota_each"] + fo["target_net_pay_each"])
be_salary = math.ceil((fixed + founder_cost) / margin_cash) if margin_cash > 0 else None

rows = "\n".join(f"| {k.capitalize()} | {eur(x['setup'])} | {eur(x['monthly'])}/month | {x['desc']} |" for k, x in t.items())
table = []
for n in (1, 3, 5, 10, 15, 20, 30):
    rev, cost = n * revenue, fixed + n * (cash_var + time_var)
    table.append(f"| {n} | {eur(rev)} | {eur(fixed + n * cash_var)} | {eur(n * time_var)} | {eur(rev - cost)} |")

md = f"""# Pricing and profit-and-loss (draft)

> Generated by `python business/pnl.py` from `business/pricing.yaml`. Edit the YAML, not this file.
> Draft to refine with Martí. Figures marked VERIFY in the YAML are still assumptions.

## What we offer

**Free trial:** about 1 week of setup, then 3–4 weeks live, no commitment. If they don't continue, we remove everything.

| Tier | Setup (one-off) | Monthly | Includes |
|---|---|---|---|
{rows}
| Ads add-on | {eur(ads['setup'])} | {eur(ads['monthly'])}/month + {eur(ads['bonus_per_qualified_lead'])} per qualified lead | {ads['desc']} |

Setup fee idea for trial clients: waive half of it if they sign within a week of the trial ending.

## Unit economics per client per month

| Item | € / month |
|---|---|
| Average revenue (tier mix {mix['base']:.0%}/{mix['pro']:.0%}/{mix['integration']:.0%}, {mix['ads_share']:.0%} with ads, setup spread over {c['months_per_client']} months) | {eur(revenue)} |
| Claude API ({v['conversations']} conversations × ${v['llm_usd_per_conversation']}) | {llm:,.0f} € |
| WhatsApp (BSP + templates) | {eur(v['whatsapp_bsp_eur'] + v['whatsapp_templates_eur'])} |
| **Cash margin** | **{eur(margin_cash)}** |
| Our time ({v['our_hours']} h/month + {c['setup_hours_per_client']} h setup spread, at {eur(rate)}/h) | {eur(time_var)} |
| **Margin after our time** | **{eur(margin_full)}** |

Fixed costs for the whole business: **{eur(fixed)}/month** ({", ".join(f"{k.replace('_', ' ')} {eur(x)}" for k, x in fx.items())}). Social security for the founders is not included yet.

## Break-even

- To cover cash costs (API, hosting, WhatsApp, fixed costs): **{be_cash} client(s)**.
- To also pay our time at {eur(rate)}/h: **{be_full} client(s)**.
- To pay {fo['count']} founders {eur(fo['target_net_pay_each'])} net each plus social security ({eur(founder_cost)}/month in total) out of the cash margin: **{be_salary} clients**. This is the number that matters.

| Clients | Revenue / month | Cash costs | Our time | Profit after our time |
|---|---|---|---|---|
{chr(10).join(table)}

## Notes

- The client pays ad spend directly on their own card, so we carry no cash risk on ads.
- Measure the real API cost per conversation during the first trial (`llm_usage` table) and update `llm_usd_per_conversation`.
- Never resell leads, and keep each lead form naming the specific client (CLAUDE.md, section 4).
"""
(HERE / "pricing.md").write_text(md, encoding="utf-8")
print(f"founder break-even {be_salary}; revenue/client {revenue:.0f} €, cash margin {margin_cash:.0f} €, break-even cash {be_cash}, full {be_full}")
